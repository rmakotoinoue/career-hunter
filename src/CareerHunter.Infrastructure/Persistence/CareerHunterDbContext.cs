using CareerHunter.Application.Common;
using CareerHunter.Domain.Assessment;
using CareerHunter.Domain.Candidates;
using CareerHunter.Domain.Catalog;
using CareerHunter.Domain.Discovery;
using CareerHunter.Domain.Notifications;
using CareerHunter.Domain.SharedKernel;
using CareerHunter.Domain.Tracking;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata;
using Npgsql;

namespace CareerHunter.Infrastructure.Persistence;

/// <summary>
/// Single write model for the modular monolith. Contexts share the database but not their
/// aggregates: cross-context references are ids, enforced by the absence of navigations.
/// </summary>
public sealed class CareerHunterDbContext(DbContextOptions<CareerHunterDbContext> options)
    : DbContext(options), IUnitOfWork
{
    public DbSet<CandidateProfile> CandidateProfiles => Set<CandidateProfile>();

    public DbSet<JobSource> JobSources => Set<JobSource>();

    public DbSet<SourceJobRecord> SourceJobRecords => Set<SourceJobRecord>();

    public DbSet<CollectionRun> CollectionRuns => Set<CollectionRun>();

    public DbSet<Employer> Employers => Set<Employer>();

    public DbSet<JobOpportunity> JobOpportunities => Set<JobOpportunity>();

    public DbSet<JobEvaluation> JobEvaluations => Set<JobEvaluation>();

    public DbSet<EvaluationPromptVersion> EvaluationPromptVersions => Set<EvaluationPromptVersion>();

    public DbSet<JobApplication> JobApplications => Set<JobApplication>();

    public DbSet<NotificationPreference> NotificationPreferences => Set<NotificationPreference>();

    public DbSet<DailyDigest> DailyDigests => Set<DailyDigest>();

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        ArgumentNullException.ThrowIfNull(modelBuilder);
        modelBuilder.ApplyConfigurationsFromAssembly(typeof(CareerHunterDbContext).Assembly);

        // All aggregate and child keys are generated by the domain, never by the store.
        // EF Core assumes Guid keys are store-generated and would otherwise treat a new child
        // added to a tracked aggregate as Modified (UPDATE) instead of Added (INSERT).
        foreach (var entityType in modelBuilder.Model.GetEntityTypes())
        {
            if (!typeof(Entity).IsAssignableFrom(entityType.ClrType))
            {
                continue;
            }

            var idProperty = entityType.FindProperty(nameof(Entity.Id));
            if (idProperty is not null)
            {
                idProperty.ValueGenerated = ValueGenerated.Never;
            }
        }

        base.OnModelCreating(modelBuilder);
    }

    /// <summary>
    /// Translates unique-constraint violations into the application-level conflict contract so a
    /// concurrent duplicate is a 409 instead of an unhandled provider exception. The database
    /// constraint stays the source of truth; this only changes how the failure is reported.
    /// </summary>
    public override async Task<int> SaveChangesAsync(CancellationToken cancellationToken = default)
    {
        try
        {
            return await base.SaveChangesAsync(cancellationToken);
        }
        catch (DbUpdateException exception) when (IsUniqueViolation(exception))
        {
            throw new ConflictException("The operation conflicts with a record that already exists.", exception);
        }
    }

    private static bool IsUniqueViolation(DbUpdateException exception)
        => exception.InnerException is PostgresException { SqlState: PostgresErrorCodes.UniqueViolation };
}
